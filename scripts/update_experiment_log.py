#!/usr/bin/env python
"""Regenerate EXPERIMENT_LOG.md from experiments/registry.yaml and the results files.

Every number in the log is computed from `results/metrics/*.csv`; only the
descriptive fields come from the registry. The script fails if a results file
is neither registered as an experiment nor listed under `not_experiments`, so
no experiment can go unlogged (`--allow-unlogged` lists them as a warning
instead). Entries whose results file does not exist yet are shown as pending.

"Best" marks the highest overall *validation* macro-F1 among the complete
ladders (all configured sizes x seeds) of a track; test metrics are reported
but never used for selection.

Usage
-----
    python scripts/update_experiment_log.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List

import pandas as pd
import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
REGISTRY = REPO_ROOT / "experiments" / "registry.yaml"
LOG = REPO_ROOT / "EXPERIMENT_LOG.md"


def summarise(path: Path) -> Dict[str, object]:
    df = pd.read_csv(path)
    largest, smallest = df["train_subset_size"].max(), df["train_subset_size"].min()
    at_max, at_min = df[df["train_subset_size"] == largest], df[df["train_subset_size"] == smallest]
    return {
        "runs": len(df),
        "seeds": df["seed"].nunique(),
        "sizes": df["train_subset_size"].nunique(),
        "size_range": f"{smallest}-{largest}" if smallest != largest else str(largest),
        "val_macro_f1": df["validation_macro_f1"].mean() if "validation_macro_f1" in df else float("nan"),
        "test_macro_f1_max": at_max["test_macro_f1"].mean(),
        "test_acc_max": at_max["test_accuracy"].mean(),
        "test_macro_f1_min": at_min["test_macro_f1"].mean(),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--allow-unlogged", action="store_true", help="Warn instead of failing on unregistered results files.")
    args = parser.parse_args()

    registry = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))
    entries: List[dict] = registry["experiments"]
    ids = [e["id"] for e in entries]
    if len(ids) != len(set(ids)):
        sys.exit(f"Duplicate experiment ids in {REGISTRY}.")
    registered = {e["results"] for e in entries} | set(registry.get("not_experiments") or {})
    unlogged = sorted(str(p.relative_to(REPO_ROOT)).replace("\\", "/") for p in (REPO_ROOT / "results" / "metrics").glob("*.csv"))
    unlogged = [p for p in unlogged if p not in registered]
    if unlogged and not args.allow_unlogged:
        sys.exit("Unlogged results files (add them to experiments/registry.yaml):\n  " + "\n  ".join(unlogged))

    rows = []
    for e in entries:
        path = REPO_ROOT / e["results"]
        stats = summarise(path) if path.exists() else None
        if stats is None:
            status = "pending"
        elif stats["runs"] < int(e.get("expected_runs", stats["runs"])):
            status = f"in progress ({stats['runs']}/{e['expected_runs']} runs)"
        else:
            status = "done"
        rows.append({**e, **(stats or {}), "status": status})
    table = pd.DataFrame(rows)

    lines = [
        "# Experiment log",
        "",
        "_Generated by `python scripts/update_experiment_log.py` from `experiments/registry.yaml` and "
        "`results/metrics/*.csv` - do not edit by hand; edit the registry and regenerate._",
        "",
        "Metrics: **val** = mean validation macro-F1 over all runs of the experiment (the selection metric); "
        "**test @max / @min** = mean test macro-F1 at the largest / smallest training size; **acc @max** = mean test "
        "accuracy at the largest size. ★ = best overall validation macro-F1 among the complete ladders of a track. "
        "Numbers are only comparable within a track (different classes and test sets).",
        "",
    ]
    for track, group in table.groupby("track", sort=False):
        complete = group[(group["status"] == "done") & (group["expected_runs"] == group["expected_runs"].max())]
        best = complete.loc[complete["val_macro_f1"].idxmax(), "id"] if not complete.empty else None
        lines += [f"## {track}", "", "| ID | Date | Group | Configuration | Runs | Sizes | val | test @max | acc @max | test @min | Conclusion |",
                  "|---|---|---|---|---:|---|---:|---:|---:|---:|---|"]
        for r in group.itertuples():
            star = " ★" if r.id == best else ""
            if r.status == "done":
                val = "-" if pd.isna(r.val_macro_f1) else f"{r.val_macro_f1:.3f}"
                metrics = f"{r.runs} | {r.size_range} | {val} | {r.test_macro_f1_max:.3f} | {r.test_acc_max:.3f} | {r.test_macro_f1_min:.3f}"
            else:
                metrics = f"{r.status} | - | - | - | - | -"
            lines.append(f"| {r.id}{star} | {r.date} | {r.group} | {r.config} | {metrics} | {r.conclusion} |")
        lines.append("")
    lines += ["## Details", ""]
    for r in table.itertuples():
        lines += [f"**{r.id}** ({r.date}, {r.track}, {r.group}) - `{r.results}` - {r.status}", "",
                  f"- Configuration: {r.config}", f"- Question: {r.question}", f"- Conclusion: {r.conclusion}", ""]
    if registry.get("not_experiments"):
        lines += ["## Results files that are not experiments", ""]
        lines += [f"- `{path}`: {why}" for path, why in registry["not_experiments"].items()]
        lines.append("")
    if unlogged:
        lines += ["## WARNING: unlogged results files", ""] + [f"- `{p}`" for p in unlogged] + [""]
    LOG.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {LOG} ({len(table)} experiments, {int((table['status'] != 'done').sum())} not yet complete)")


if __name__ == "__main__":
    main()
