"""Experiment orchestration: wires together the shared data pipeline,
a model implementing :class:`emotion_ait.interfaces.EmotionClassifier`,
and the shared evaluation protocol.

This module is deliberately model-agnostic: it works today with the
baselines in :mod:`emotion_ait.baselines`, and will work unchanged once
:mod:`emotion_ait.mdl_classifier` / :mod:`emotion_ait.lstm_classifier`
are implemented, since all three share the same interface.
"""

from __future__ import annotations

from typing import Optional

import pandas as pd

from .config import Config
from .evaluation import ResultRecord, Timer, append_result, compute_metrics, save_predictions, warn_if_missing_classes
from .interfaces import EmotionClassifier
from .sampling import load_subset_dataframe


def run_experiment(
    model: EmotionClassifier,
    model_name: str,
    subset_name: str,
    processed_df: pd.DataFrame,
    config: Config,
    config_summary: Optional[dict] = None,
    save_test_predictions: bool = True,
) -> ResultRecord:
    """Run one full train/evaluate cycle for a model on a named training
    subset, and append the result to the shared results CSV.

    Parameters
    ----------
    model:
        Any fitted-or-unfitted :class:`EmotionClassifier`. ``fit`` is
        called by this function; the caller should not pre-fit it.
    model_name:
        Human-readable model identifier for the results schema (e.g.
        ``"majority_baseline"``, ``"mdl"``, ``"lstm"``).
    subset_name:
        Name of a subset previously generated by
        :func:`emotion_ait.sampling.generate_all_subsets` (e.g.
        ``"train_pct10"``).
    processed_df:
        The full processed dataset (all splits), as produced by
        :mod:`emotion_ait.preprocessing`.
    config:
        Shared project configuration.
    config_summary:
        Optional free-form dict of hyperparameters to embed in the
        results schema for reproducibility.
    save_test_predictions:
        If True (default), also persist one row per test example (true
        vs. predicted label, and per-class description lengths when the
        model exposes them) via
        :func:`emotion_ait.evaluation.save_predictions`, for qualitative
        / error analysis.
    """
    train_df = load_subset_dataframe(subset_name, processed_df, config)
    validation_df = processed_df[processed_df["original_split"] == "validation"].reset_index(drop=True)
    test_df = processed_df[processed_df["original_split"] == "test"].reset_index(drop=True)

    id_to_label = config.target_task.id_to_label

    with Timer() as train_timer:
        model.fit(train_df, validation_data=validation_df)
    train_time = train_timer.elapsed or 0.0

    validation_macro_f1 = None
    if not validation_df.empty:
        val_preds = model.predict(validation_df["text"].tolist())
        warn_if_missing_classes(validation_df["label"].tolist(), id_to_label)
        val_metrics = compute_metrics(validation_df["label"].tolist(), val_preds, id_to_label)
        validation_macro_f1 = val_metrics["macro_f1"]

    with Timer() as inference_timer:
        test_preds = model.predict(test_df["text"].tolist())
    inference_time = inference_timer.elapsed or 0.0

    warn_if_missing_classes(test_df["label"].tolist(), id_to_label)
    test_metrics = compute_metrics(test_df["label"].tolist(), test_preds, id_to_label)

    if save_test_predictions and not test_df.empty:
        description_lengths = None
        describe = getattr(model, "description_lengths", None)
        if callable(describe):
            description_lengths = describe(test_df["text"].tolist())
        save_predictions(
            model_name=model_name,
            subset_name=subset_name,
            seed=config.sampling.seed,
            example_ids=test_df["example_id"].tolist(),
            texts=test_df["text"].tolist(),
            y_true=test_df["label"].tolist(),
            y_pred=test_preds,
            label_names=id_to_label,
            results_dir=config.paths.results_dir,
            description_lengths=description_lengths,
        )

    with open(config.paths.subsets_dir / f"{subset_name}.json", "r", encoding="utf-8") as fh:
        import json

        subset_meta = json.load(fh)

    record = ResultRecord(
        model_name=model_name,
        train_subset_name=subset_name,
        train_subset_percentage=subset_meta.get("percentage"),
        train_subset_size=len(train_df),
        seed=config.sampling.seed,
        config_summary=config_summary or {},
        test_accuracy=test_metrics["accuracy"],
        test_macro_f1=test_metrics["macro_f1"],
        test_per_class=test_metrics["per_class"],
        train_time_seconds=train_time,
        inference_time_seconds=inference_time,
        validation_macro_f1=validation_macro_f1,
    )
    append_result(record, config.paths.results_dir / "metrics")
    return record
